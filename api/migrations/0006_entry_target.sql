-- سقف شرکت‌کننده: دومین شرط بسته‌شدن یک دوره.
--
-- تا اینجا تنها راه بسته شدن یک دوره گذشتنِ closes_at بود. حالا دو شرط
-- موازی داریم و هر کدام زودتر رخ دهد دوره را می‌بندد:
--   ۱) رسیدن تعداد حدس‌های *پرداخت‌شدهٔ* ثبت‌شده به entry_target
--   ۲) رسیدن به closes_at
-- هر دو مقدار هنگام تعریف مسابقه تعیین می‌شوند و قابل ویرایش‌اند.
--
-- چرا «بسته شدن» و نه یک وضعیت تازه: در این کدبیس «آمادهٔ داوری» دقیقاً
-- یعنی status='closed' — گیت‌های Reveal/Settle همه همین را می‌خوانند
-- (judging.go). افزودن وضعیت تازه یعنی تغییر CHECK مهاجرت ۰۰۰۱ و بازنویسی
-- آن گیت‌ها، بدون اینکه چیزی به دست بیاید.
--
-- چرا فایل جدا و نه افزودن به ۰۰۰۵: Migrate هر فایل را با نامش در
-- schema_migrations کلید می‌کند و اگر قبلاً اجرا شده باشد از رویش رد می‌شود
-- (store.go). ۰۰۰۵ پیش از این ویژگی نوشته و اجرا شده بود؛ افزودن ستون به آن
-- یعنی روی هر پایگاه دادهٔ موجود ستون هرگز ساخته نمی‌شود، در حالی که
-- compCols در catalog.go آن را SELECT می‌کند — یعنی کل API کاتالوگ با
-- خطای «column does not exist» می‌افتد، بدون اینکه هیچ خطای مهاجرتی به آن
-- اشاره کند. همان درسی که ۰۰۰۳ در ابتدای خودش ثبت کرده است.

-- ---------- ۱) ستون سقف شرکت‌کننده ----------
-- ۰ یعنی «بدون سقف» — همان قراردادی که max_entries_user دارد، تا دو ستون
-- عددیِ همسایه دو معنای متفاوت برای صفر نداشته باشند.
--
-- پیش‌فرض ۲۰۰۰۰ است چون قاعدهٔ کسب‌وکار همین است و ردیف‌های موجود هم باید
-- همان رفتار را بگیرند. DEFAULT روی ستون می‌ماند تا INSERT‌هایی که این ستون
-- را نمی‌نویسند هم همان قاعده را بگیرند، نه «بدون سقف» را.
ALTER TABLE competitions
    ADD COLUMN IF NOT EXISTS entry_target INT NOT NULL DEFAULT 20000;

DO $$ BEGIN
    ALTER TABLE competitions
        ADD CONSTRAINT chk_comp_entry_target CHECK (entry_target >= 0);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

COMMENT ON COLUMN competitions.entry_target IS
    'سقف تعداد حدس پرداخت‌شده؛ با رسیدن به آن مسابقه بسته و آمادهٔ داوری می‌شود. ۰ = بدون سقف';

-- ---------- ۲) شمارش سریع حدس‌های شمارش‌پذیر ----------
-- سقف فقط حدس‌هایی را می‌شمارد که یا رایگان‌اند یا سفارششان پرداخت شده.
-- Checkout ورودی‌ها را همراه سفارشِ pending درج می‌کند و هیچ چیز سفارش
-- pending را منقضی نمی‌کند؛ با شمارش خام، یک اسکریپت می‌توانست دوره را با
-- ۲۰٬۰۰۰ حدس پرداخت‌نشده ببندد و عملاً کل مسابقه را از کار بیندازد.
CREATE INDEX IF NOT EXISTS idx_entries_comp_order
    ON entries(competition_id, order_id);
